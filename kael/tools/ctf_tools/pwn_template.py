@function_tool(timeout=15, strict_mode=False)
async def pwn_template(  # type: ignore[no-untyped-def]
    ctx,
    binary: str = "chall",
    host: str = "target.example.com",
    port: int = 1337,
    offset: int = 0,
) -> str:
    """Generate a pwntools exploit template.

    Returns a Python script that the agent can write to a file and
    execute via ``exec_command``. Saves the 30-line boilerplate every
    pwn challenge needs.

    Args:
        binary: Binary name (default ``chall``). Should be in CWD when
            the script runs.
        host: Remote host.
        port: Remote port.
        offset: Padding to return address. If unknown, leave 0 and
            discover via ``pwn cyclic``.

    Returns:
        Python source as a string. Use ``write_note`` / sandbox file
        writes to persist it.
    """
    return render_template(binary=binary, host=host, port=port, offset=offset)


def render_template(  # type: ignore[no-untyped-def]
    binary: str = "chall",
    host: str = "target.example.com",
    port: int = 1337,
    offset: int = 0,
) -> str:
    """Sync impl of pwn_template for direct unit-test use."""
    return _TEMPLATE.format(
        challenge=binary,
        binary=binary,
        host=host,
        port=port,
        offset=offset,
    )
